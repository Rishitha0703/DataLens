"""
ai_insights.py
--------------
Connects with Google Gemini to generate high-value, human-readable analytical
insights from the statistical summary produced by `analytics.py`.

Features:
  * Uses the official `google-genai` SDK with fallback to `google.generativeai`.
  * Automatic API key discovery from `GEMINI_API_KEY` or `GOOGLE_API_KEY` env vars / .env.
  * Robust error handling and intelligent heuristic fallback if API key is absent.
  * Formatted markdown output with executive summary, quality observations,
    distribution patterns, correlation insights, and actionable recommendations.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

# Load environment variables from .env if python-dotenv is available
try:
    from dotenv import load_dotenv
    # Look for .env in current working dir and DataLens directory
    load_dotenv(Path(__file__).resolve().parent / ".env")
    load_dotenv()
except ImportError:
    pass

# Try importing the new google-genai SDK, then fallback to google-generativeai
GENAI_SDK = None
try:
    from google import genai
    from google.genai import types
    GENAI_SDK = "google-genai"
except ImportError:
    try:
        import google.generativeai as legacy_genai
        GENAI_SDK = "google-generativeai"
    except ImportError:
        GENAI_SDK = None

DEFAULT_MODEL = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")


def get_api_key(explicit_key: str | None = None) -> str | None:
    """Resolve Gemini API key from parameter or environment variables."""
    if explicit_key and explicit_key.strip():
        return explicit_key.strip()
    return (
        os.getenv("GEMINI_API_KEY")
        or os.getenv("GOOGLE_API_KEY")
        or None
    )


def is_gemini_configured(explicit_key: str | None = None) -> bool:
    """Check if Gemini SDK is installed and an API key is available."""
    if GENAI_SDK is None:
        return False
    key = get_api_key(explicit_key)
    return bool(key and len(key) > 5)


def build_analysis_prompt(analysis: dict[str, Any], title: str = "Uploaded Dataset") -> str:
    """Format the analytics summary dictionary into a structured prompt for Gemini."""
    overview = analysis.get("overview", {})
    col_types = analysis.get("column_types", {})
    quality = analysis.get("data_quality", {})
    num_stats = analysis.get("numeric_stats", {})
    cat_stats = analysis.get("categorical_stats", {})
    corr = analysis.get("correlation", {})

    prompt_lines = [
        f"You are a Senior Data Scientist and Business Intelligence Consultant analyzing '{title}'.",
        "Below is a complete statistical summary and data quality profile generated by DataLens.",
        "Synthesize these findings into an executive-ready analytical report.",
        "",
        "### DATASET PROFILE",
        f"- Rows: {overview.get('rows', 0)} (Original: {overview.get('original_rows', 0)})",
        f"- Columns: {overview.get('columns', 0)} (Original: {overview.get('original_columns', 0)})",
        f"- Numerical columns ({len(col_types.get('numerical', []))}): {', '.join(col_types.get('numerical', [])) or 'None'}",
        f"- Categorical columns ({len(col_types.get('categorical', []))}): {', '.join(col_types.get('categorical', [])) or 'None'}",
        f"- Datetime columns ({len(col_types.get('datetime', []))}): {', '.join(col_types.get('datetime', [])) or 'None'}",
        f"- Approximate memory footprint: {overview.get('memory_kb', 0)} KB",
        "",
        "### DATA QUALITY & PREPROCESSING AUDIT",
        f"- Duplicates found: {quality.get('duplicates_found', 0)}, removed: {quality.get('duplicates_removed', 0)}",
        f"- Dropped mostly-empty columns: {quality.get('dropped_columns', []) or 'None'}",
        f"- Type conversions: {quality.get('converted_types', {}) or 'None'}",
        f"- Imputed columns: {len(quality.get('imputed', []))} column(s) imputed",
    ]

    for imp in quality.get("imputed", []):
        prompt_lines.append(f"  * {imp.get('column')}: {imp.get('count')} missing cells filled with {imp.get('strategy')} ({imp.get('value')})")

    missing_before = [m for m in quality.get("missing_before_cleaning", []) if m.get("missing", 0) > 0]
    if missing_before:
        prompt_lines.append("- Missing values before cleaning:")
        for m in missing_before[:8]:
            prompt_lines.append(f"  * {m.get('column')}: {m.get('missing')} missing ({m.get('missing_pct')}%)")
    else:
        prompt_lines.append("- Missing values before cleaning: None detected.")

    if num_stats:
        prompt_lines.append("")
        prompt_lines.append("### NUMERICAL DISTRIBUTIONS & METRICS")
        for col, s in list(num_stats.items())[:10]:
            prompt_lines.append(
                f"- **{col}**: mean={s.get('mean'):.2f}, median={s.get('median'):.2f}, "
                f"std={s.get('std'):.2f if s.get('std') is not None else 'N/A'}, "
                f"range=[{s.get('min'):.2f} to {s.get('max'):.2f}], "
                f"skew={s.get('skew'):.2f if s.get('skew') is not None else 'N/A'}, "
                f"outliers={s.get('outlier_count', 0)}"
            )

    if cat_stats:
        prompt_lines.append("")
        prompt_lines.append("### CATEGORICAL FREQUENCIES")
        for col, c in list(cat_stats.items())[:8]:
            if c.get("likely_identifier"):
                prompt_lines.append(f"- **{col}**: High-cardinality identifier ({c.get('unique')} unique values).")
            else:
                top_vals = [f"'{t['value']}' ({t['pct']}%)" for t in c.get("top_frequency", [])[:4]]
                prompt_lines.append(f"- **{col}** ({c.get('unique')} unique): top values: {', '.join(top_vals)}")

    top_pairs = corr.get("top_pairs", [])
    if top_pairs:
        prompt_lines.append("")
        prompt_lines.append("### KEY CORRELATIONS (PEARSON)")
        for pair in top_pairs[:6]:
            prompt_lines.append(
                f"- {pair.get('a')} × {pair.get('b')}: r = {pair.get('r'):.3f} "
                f"({pair.get('strength')} {pair.get('direction')})"
            )

    prompt_lines.extend([
        "",
        "### INSTRUCTIONS FOR YOUR ANALYSIS",
        "Provide your analysis structured with the following 4 sections in clear Markdown (use `##` headers):",
        "## 1. Executive Summary & Dataset Characterization",
        "Summarize what this data captures, sample size adequacy, and primary takeaways in 2 concise paragraphs.",
        "",
        "## 2. Data Quality & Preprocessing Assessment",
        "Evaluate data cleanliness, missingness patterns, impact of duplicate removal, and validity of imputed fields.",
        "",
        "## 3. Key Statistical Trends & Outlier Anomalies",
        "Highlight significant distribution shapes (skewness, variance), notable outliers, and dominant categorical segments.",
        "",
        "## 4. Relationship Analysis & Strategic Recommendations",
        "Interpret the strongest correlations, business or scientific implications, and 3 actionable next steps or modeling strategies.",
        "",
        "Style Guidelines:",
        "- Be concrete, citing actual figures and column names from above.",
        "- Do not use generic filler or state the obvious.",
        "- Professional, crisp, insight-dense tone.",
    ])

    return "\n".join(prompt_lines)


def generate_heuristic_insights(analysis: dict[str, Any]) -> str:
    """Generate an automated rule-based analytical summary when Gemini API key is not configured."""
    overview = analysis.get("overview", {})
    quality = analysis.get("data_quality", {})
    num_stats = analysis.get("numeric_stats", {})
    cat_stats = analysis.get("categorical_stats", {})
    corr = analysis.get("correlation", {})

    rows = overview.get("rows", 0)
    cols = overview.get("columns", 0)
    num_cols = len(num_stats)
    cat_cols = len(cat_stats)

    lines = [
        "> **Note:** Gemini API key is not set. Showing automated rule-based analytical summary. "
        "To enable full generative AI analysis, set `GEMINI_API_KEY` in your environment or `.env` file.",
        "",
        "## 1. Dataset Overview",
        f"The dataset contains **{rows:,} records** across **{cols} features** "
        f"({num_cols} numerical, {cat_cols} categorical).",
    ]

    # Quality insights
    dups = quality.get("duplicates_removed", 0)
    imputed = quality.get("imputed", [])
    dropped = quality.get("dropped_columns", [])

    lines.append("")
    lines.append("## 2. Data Quality & Hygiene")
    if dups:
        lines.append(f"- **Duplicates:** {dups:,} duplicate rows were identified and removed.")
    else:
        lines.append("- **Duplicates:** No duplicate records were detected.")

    if dropped:
        lines.append(f"- **Sparse Features:** Columns dropped due to high missingness: {', '.join(dropped)}.")
    if imputed:
        imp_summary = [f"{i['column']} ({i['count']} via {i['strategy']})" for i in imputed]
        lines.append(f"- **Imputations:** Handled missing values in: {', '.join(imp_summary)}.")
    else:
        lines.append("- **Completeness:** No missing values required imputation after initial cleaning.")

    # Distribution insights
    if num_stats:
        lines.append("")
        lines.append("## 3. Distribution Highlights & Outliers")
        outlier_cols = [(col, s.get("outlier_count", 0)) for col, s in num_stats.items() if s.get("outlier_count", 0) > 0]
        if outlier_cols:
            outlier_desc = ", ".join(f"**{col}** ({count} outliers)" for col, count in outlier_cols)
            lines.append(f"- **Outlier Detection:** Outliers identified in: {outlier_desc}.")
        else:
            lines.append("- **Outlier Detection:** All numerical values fall within standard 1.5× IQR fences.")

        skewed_cols = [(col, s.get("skew")) for col, s in num_stats.items() if s.get("skew") is not None and abs(s.get("skew", 0)) > 1.0]
        if skewed_cols:
            skew_desc = ", ".join(f"**{col}** (skew = {sk:.2f})" for col, sk in skewed_cols)
            lines.append(f"- **Skewness:** Significant asymmetry detected in: {skew_desc}.")

    # Correlation insights
    top_pairs = corr.get("top_pairs", [])
    if top_pairs:
        lines.append("")
        lines.append("## 4. Key Relationships & Recommendations")
        strong = [p for p in top_pairs if abs(p.get("r", 0)) >= 0.5]
        if strong:
            strong_desc = ", ".join(f"**{p['a']}** & **{p['b']}** (r = {p['r']:.2f}, {p['direction']})" for p in strong)
            lines.append(f"- **Strong Associations:** {strong_desc}.")
        else:
            lines.append(f"- **Strongest Pair:** **{top_pairs[0]['a']}** and **{top_pairs[0]['b']}** (r = {top_pairs[0]['r']:.2f}).")
        lines.append("- **Recommended Next Steps:** Consider evaluating non-linear interactions, scaling features with high skew, and applying segmentation based on dominant categorical groupings.")

    return "\n\n".join(lines)


def generate_insights(
    analysis: dict[str, Any],
    api_key: str | None = None,
    model: str | None = None,
    dataset_name: str = "Uploaded Dataset",
) -> str:
    """
    Generate comprehensive analytical insights from dataset analysis.

    If a Gemini API key is available, calls Gemini model (default: gemini-2.5-flash).
    Otherwise, gracefully falls back to structured heuristic insights.
    """
    key = get_api_key(api_key)
    model_name = model or DEFAULT_MODEL

    if not key or GENAI_SDK is None:
        return generate_heuristic_insights(analysis)

    prompt = build_analysis_prompt(analysis, title=dataset_name)

    try:
        if GENAI_SDK == "google-genai":
            client = genai.Client(api_key=key)
            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
                config=types.GenerateContentConfig(
                    temperature=0.3,
                    max_output_tokens=2048,
                ) if hasattr(types, "GenerateContentConfig") else None,
            )
            return response.text or generate_heuristic_insights(analysis)

        elif GENAI_SDK == "google-generativeai":
            legacy_genai.configure(api_key=key)
            model_inst = legacy_genai.GenerativeModel(model_name)
            response = model_inst.generate_content(prompt)
            return response.text or generate_heuristic_insights(analysis)

    except Exception as exc:
        err_msg = str(exc)
        fallback = generate_heuristic_insights(analysis)
        return (
            f"> **Gemini API Notice:** Failed to generate live AI insights ({err_msg}). "
            f"Falling back to heuristic summary below.\n\n{fallback}"
        )

    return generate_heuristic_insights(analysis)


def generate_insights_payload(
    analysis: dict[str, Any],
    api_key: str | None = None,
    model: str | None = None,
    dataset_name: str = "Uploaded Dataset",
) -> dict[str, Any]:
    """Return insights with status metadata for API consumers."""
    key = get_api_key(api_key)
    configured = bool(key and GENAI_SDK is not None)
    insights_text = generate_insights(
        analysis=analysis,
        api_key=key,
        model=model,
        dataset_name=dataset_name,
    )
    return {
        "gemini_configured": configured,
        "model_used": (model or DEFAULT_MODEL) if configured else "heuristic_fallback",
        "insights": insights_text,
    }


